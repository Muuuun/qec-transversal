@pytest.mark.parametrize("name", ["steane", "c4-22", "toric-4", "surface-5"])
def test_singleton_partition_reproduces_the_strict_group(name: str) -> None:
    """``GL(2,2) = Sp(2,2)``: at singleton cells the symplectic cut is free."""

    code = _stacked(CSSCode(*REGISTRY[name].build()))
    singletons = [(q,) for q in range(code.n)]
    partition = partition_clifford_group(code, singletons, method="enumeration")
    strict = strict_transversal_clifford(code, method="general")
    assert partition.completeness is Completeness.COMPLETE
    assert strict.completeness is Completeness.COMPLETE
    assert partition.group_order == strict.group_order
    assert partition.logical_group_order == strict.logical_group_order


@pytest.mark.parametrize(
    "name,cells",
    [
        ("steane", [(0, 1), (2, 3), (4, 5), (6,)]),
        ("c4-22", [(0, 1), (2, 3)]),
        ("c6-22", [(0, 1), (2, 3), (4, 5)]),
        ("iceberg-8", [(0, 1), (2, 3), (4, 5), (6, 7)]),
    ],
)
def test_structured_and_enumeration_partition_routes_are_consistent(name, cells) -> None:
    """The certified unit-group route and the ``2^dim`` sweep, side by side.

    Both routes may legitimately decline -- the algebra can outgrow the
    enumeration cap, and the unit group can outgrow the group-enumeration cap
    used for the symplectic cut.  What must hold unconditionally is that a
    decline is *honest* (``UNKNOWN`` with no order) and that when both routes
    finish they agree.
    """

    code = _stacked(CSSCode(*REGISTRY[name].build()))
    structured = partition_clifford_group(code, cells, method="structure")
    enumerated = partition_clifford_group(code, cells, method="enumeration")

    for result in (structured, enumerated):
        if result.completeness is Completeness.UNKNOWN:
            assert result.group_order is None
            assert result.logical_group_order is None

    if Completeness.UNKNOWN in (structured.completeness, enumerated.completeness):
        pytest.skip(f"{name}: a route declined honestly on this instance")
    assert structured.group_order == enumerated.group_order
    assert structured.logical_group_order == enumerated.logical_group_order


def test_structured_and_enumeration_partition_routes_agree_where_both_finish() -> None:
    """At least one instance must exercise the agreement, not just the skip."""

    for name, cells, want in (
        ("steane", [(0, 1), (2, 3), (4, 5), (6,)], 48),
        ("c4-22", [(0, 1), (2, 3)], 384),
    ):
        code = _stacked(CSSCode(*REGISTRY[name].build()))
        structured = partition_clifford_group(code, cells, method="structure")
        enumerated = partition_clifford_group(code, cells, method="enumeration")
        assert structured.completeness is Completeness.COMPLETE
        assert enumerated.completeness is Completeness.COMPLETE
        assert structured.group_order == enumerated.group_order == want
        assert structured.logical_group_order == enumerated.logical_group_order


def test_two_local_partition_strictly_contains_the_strict_group() -> None:
    """Coarsening the partition can only add gates, never remove them."""

    code = _stacked(CSSCode(*REGISTRY["c4-22"].build()))
    strict = partition_clifford_group(code, [(0,), (1,), (2,), (3,)])
    pairs = partition_clifford_group(code, [(0, 1), (2, 3)])
    assert strict.group_order == 6 and pairs.group_order == 384
    assert pairs.group_order % strict.group_order == 0  # Lagrange
    assert pairs.logical_group_order == 48
    assert strict.logical_group_order == 6


