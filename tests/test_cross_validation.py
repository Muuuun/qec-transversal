# 3. logical-action consistency, for every backend
# ---------------------------------------------------------------------------


def _recheck_stabilizer_generator(code: StabilizerCode, matrix: np.ndarray) -> np.ndarray:
    """Independently: preserve the stabilizer, re-derive the logical action.

    Deliberately does not call ``logical.action.project_to_logical`` -- this
    is the second opinion, written out longhand.
    """

    n = code.n
    assert is_symplectic(matrix, qubits=n), "physical matrix is not symplectic"
    image = gf2_matmul(code.h, matrix)
    assert not rowspace_residues(image, code.h).any(), "stabilizer not preserved"
    if code.k == 0:
        return np.zeros((0, 0), dtype=np.uint8)
    images = gf2_matmul(code.logical, matrix)
    action = np.zeros((2 * code.k, 2 * code.k), dtype=np.uint8)
    for row_index in range(2 * code.k):
        for j in range(code.k):
            action[row_index, j] = symplectic_product(
                images[row_index], code.logical[code.k + j], qubits=n
            )[0, 0]
            action[row_index, code.k + j] = symplectic_product(
                images[row_index], code.logical[j], qubits=n
            )[0, 0]
    residue = (images ^ gf2_matmul(action, code.logical)) & 1
    assert not rowspace_residues(residue, code.h).any(), "logical residue outside S"
    assert is_symplectic(action, qubits=code.k), "logical action is not symplectic"
    return action


@pytest.mark.parametrize("name", ["steane", "c4-22", "cube-832"])
def test_every_strict_generator_survives_an_independent_recheck(name: str) -> None:
    code = _stacked(CSSCode(*REGISTRY[name].build()))
    result = strict_transversal_clifford(code)
    assert result.generators
    for record in result.generators:
        entries = np.zeros(4 * code.n, dtype=np.uint8)
        for i, block in enumerate(record.blocks):
            entries[4 * i : 4 * i + 4] = block
        matrix = _block_action_matrix(entries, code.n)
        action = _recheck_stabilizer_generator(code, matrix)
        assert np.array_equal(action, record.logical_symplectic)


def _recheck_css_generator(css: CSSCode, matrix: np.ndarray) -> np.ndarray:
    """The same second opinion, in the CSS code's *own* logical basis.

    ``CSSCode`` and ``StabilizerCode`` build their paired logical bases by
    different constructions, so the induced logical matrices are conjugate but
    not equal; comparing a CSS generator's action against the general code
    object's basis would be a basis mismatch, not a disagreement.
    """

    n = css.n
    assert is_symplectic(matrix, qubits=n), "physical matrix is not symplectic"
    image = gf2_matmul(css.stabilizer, matrix)
    assert not rowspace_residues(image, css.stabilizer).any(), "stabilizer not preserved"
    if css.k == 0:
        return np.zeros((0, 0), dtype=np.uint8)
    images = gf2_matmul(css.logical, matrix)
    action = np.zeros((2 * css.k, 2 * css.k), dtype=np.uint8)
    for row_index in range(2 * css.k):
        for j in range(css.k):
            action[row_index, j] = symplectic_product(
                images[row_index], css.logical[css.k + j], qubits=n
            )[0, 0]
            action[row_index, css.k + j] = symplectic_product(
                images[row_index], css.logical[j], qubits=n
            )[0, 0]
    residue = (images ^ gf2_matmul(action, css.logical)) & 1
    assert not rowspace_residues(residue, css.stabilizer).any(), "residue outside S"
    assert is_symplectic(action, qubits=css.k), "logical action is not symplectic"
    return action


@pytest.mark.parametrize("name", ["steane", "qrm15", "grid-4x6", "c4-22", "tesseract"])
def test_every_css_shear_generator_survives_an_independent_recheck(name: str) -> None:
    css = CSSCode(*REGISTRY[name].build())
    result = strict_transversal_clifford(css, method="css")
    for record in result.generators:
        matrix = shear_matrix(record.family, record.parameter)
        action = _recheck_css_generator(css, matrix)
        assert np.array_equal(action, record.logical_symplectic)


def test_logical_generators_of_every_public_entry_point_are_symplectic() -> None:
    """Whatever a backend returns as a logical image must live in Sp(2k, 2)."""

    from qec_transversal import (
        diagonal_transversal_gates,
        matching_clifford_group,
        one_block_clifford_group,
    )

    css = CSSCode(*REGISTRY["steane"].build())
    results = [
        strict_transversal_clifford(css),
        strict_transversal_clifford(css, method="general"),
        partition_clifford_group(css, [(q,) for q in range(css.n)]),
        matching_clifford_group(css, np.arange(css.n)),
        diagonal_transversal_gates(css, level=3),
        one_block_clifford_group(css, name="steane", time_budget_s=20.0),
    ]
    for result in results:
        for matrix in result.logical_generators:
            assert is_symplectic(matrix, qubits=css.k), result.method


