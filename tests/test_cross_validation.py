"""Cross-validation between independent solvers.

Each test here computes the *same mathematical object* by two routes that share
no code path, and asserts they agree.  These are the tests that would catch a
refactor silently changing a convention: the specialised CSS solvers know
nothing about preservation algebras, the general solver knows nothing about
shears, and brute force knows nothing about either.

Invariants covered:

* CSS shear solver == general preservation-algebra solver, physically and
  logically, on every CSS code where both apply;
* singleton-cell ``partition_clifford_group`` == ``strict_transversal_clifford``;
* the structured unit-group route == the ``2^dim`` enumeration route;
* every generator returned by any backend really preserves the code, its
  logical action re-derives independently, and that action is symplectic;
* an exhausted budget reports ``UNKNOWN`` with no group order, never a small
  number.
"""

import itertools

import numpy as np
import pytest

from qec_transversal import (
    REGISTRY,
    Completeness,
    CSSCode,
    StabilizerCode,
    five_qubit_code,
    partition_clifford_group,
    strict_transversal_clifford,
)
from qec_transversal.algebra.preservation import _SL22, _block_action_matrix
from qec_transversal.ansatz.strict_css import shear_matrix
from qec_transversal.logical.group import generated_group_order
from qec_transversal.utils.gf2 import (
    gf2_inverse,
    gf2_matmul,
    rank,
    reduce_rows,
    rowspace_residues,
    rref,
)
from qec_transversal.utils.symplectic import is_symplectic, symplectic_product

#: CSS codes small enough for the general route's 2^dim enumeration and for
#: dense physical-group closure.
SMALL_CSS = ["steane", "c4-22", "c6-22", "qrm15", "toric-4", "surface-5", "cube-832"]


def _stacked(css: CSSCode) -> StabilizerCode:
    return css.to_stabilizer_code()


def _random_css(rng, n, rows):
    """A random CSS pair with ``H_X H_Z^T = 0``."""

    h_x = rng.integers(0, 2, size=(rows, n), dtype=np.uint8)
    from qec_transversal.utils.gf2 import nullspace

    perp = nullspace(h_x)
    if perp.shape[0] == 0:
        return None
    picks = rng.integers(0, 2, size=(rows, perp.shape[0]), dtype=np.uint8)
    h_z = gf2_matmul(picks, perp)
    return h_x, h_z


def _closure(k: int, generators) -> set:
    """Every element of the group generated by ``generators``, as bytes keys."""

    identity = np.eye(2 * k, dtype=np.uint8)
    seen = {identity.tobytes()}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in generators:
            product = gf2_matmul(current, generator)
            if product.tobytes() not in seen:
                seen.add(product.tobytes())
                frontier.append(product)
    return seen


def _logical_change_of_basis(css: CSSCode) -> np.ndarray:
    r"""``T`` with ``L_stabilizer = T L_css`` in ``S^\perp / S``.

    The two code objects choose different representatives of the logical Pauli
    basis, so a physical gate's logical matrix ``A`` in the stabilizer basis is
    ``T^{-1} A T`` in the CSS basis.
    """

    from qec_transversal.utils.gf2 import coordinates_over

    stabilizer = css.to_stabilizer_code()
    ambient = np.vstack([css.logical, css.stabilizer])
    rows = []
    for row in stabilizer.logical:
        coefficients = coordinates_over(ambient, row)
        assert coefficients is not None, "logical row outside the normalizer span"
        rows.append(coefficients[: 2 * css.k])
    return np.asarray(rows, dtype=np.uint8)


def _random_stabilizer(rng, n, m):
    rows = np.zeros((0, 2 * n), dtype=np.uint8)
    tries = 0
    while rows.shape[0] < m and tries < 200:
        tries += 1
        candidate = rng.integers(0, 2, size=2 * n, dtype=np.uint8)
        if not candidate.any():
            continue
        if rows.shape[0] and symplectic_product(rows, candidate[None, :], qubits=n).any():
            continue
        stacked = np.vstack([rows, candidate])
        if rank(stacked) > rows.shape[0]:
            rows = stacked
    return rows


# ---------------------------------------------------------------------------
# 1. specialised CSS solver vs the general preservation-algebra solver
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("name", SMALL_CSS)
def test_css_and_general_strict_solvers_agree(name: str) -> None:
    """Two independent computations of the strict-transversal group.

    The CSS route solves two GF(2) kernels for the diagonal shear families and
    invokes Albert's structure theorem to claim they generate everything.  The
    general route builds the singleton preservation algebra and takes its unit
    group, with no notion of a shear.  Both must be COMPLETE, must induce the
    same logical group, and -- checked here explicitly -- the physical group
    generated by the CSS shear layers must have exactly the order the general
    route reports.
    """

    css = CSSCode(*REGISTRY[name].build())
    specialised = strict_transversal_clifford(css, method="css")
    general = strict_transversal_clifford(css, method="general")

    assert specialised.completeness is Completeness.COMPLETE
    assert general.completeness is Completeness.COMPLETE
    assert specialised.logical_group_order == general.logical_group_order
    assert specialised.logical_group_order_is_exact
    assert general.logical_group_order_is_exact

    # The two engines build their paired logical bases by different
    # constructions, so their logical matrices are conjugate rather than
    # equal.  Transport the general route's group into the CSS basis and then
    # demand equality as SETS -- a much stronger statement than equal orders.
    if css.k:
        change = _logical_change_of_basis(css)
        change_inverse = gf2_inverse(change)
        transported = [
            gf2_matmul(gf2_matmul(change_inverse, matrix), change)
            for matrix in general.logical_generators
        ]
        assert _closure(css.k, list(specialised.logical_generators)) == _closure(
            css.k, transported
        )

    # physical side: close the CSS shear layers as dense 2n x 2n matrices
    analysis = specialised.analysis
    shears = [
        shear_matrix(g.family, g.parameter)
        for g in analysis.generators
    ]
    shears = [m for m in shears if not np.array_equal(m, np.eye(2 * css.n, dtype=np.uint8))]
    closure = generated_group_order(shears, cap=200_000)
    assert closure.exact
    assert closure.order == general.group_order


def test_general_strict_solver_matches_brute_force_on_small_codes() -> None:
    """Exact algebra vs exhaustive enumeration of all 6^n Clifford assignments.

    Covers CSS and non-CSS codes together, including the [[5,1,3]] perfect
    code, whose strict group is the order-3 cyclic (SH)^{otimes 5}.
    """

    rng = np.random.default_rng(20260820)
    codes = [five_qubit_code()]
    for n in (2, 3, 4):
        for _ in range(3):
            rows = _random_stabilizer(rng, n, int(rng.integers(1, n + 1)))
            if rows.shape[0]:
                codes.append(StabilizerCode(rows))
    for name in ("steane", "c4-22"):
        codes.append(_stacked(CSSCode(*REGISTRY[name].build())))

    for code in codes:
        if code.n > 5:
            continue
        result = strict_transversal_clifford(code)
        assert result.completeness is Completeness.COMPLETE
        reduced, pivots = rref(code.h)
        want = 0
        for combo in itertools.product(range(6), repeat=code.n):
            entries = np.zeros(4 * code.n, dtype=np.uint8)
            for i, g in enumerate(combo):
                entries[4 * i : 4 * i + 4] = _SL22[g]
            matrix = _block_action_matrix(entries, code.n)
            if not reduce_rows(gf2_matmul(code.h, matrix), reduced, pivots).any():
                want += 1
        assert result.group_order == want, f"n={code.n}"


