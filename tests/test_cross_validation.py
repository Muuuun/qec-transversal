def test_exhausted_budget_reports_unknown_not_a_small_group() -> None:
    """A capped computation must never look like a certified small answer."""

    code = _stacked(CSSCode(*REGISTRY["steane"].build()))
    starved = strict_transversal_clifford(code, method="general", dim_cap=0)
    if starved.completeness is Completeness.COMPLETE:
        # the structured route succeeded without enumeration; then it must be
        # right, not merely finished
        assert starved.group_order == strict_transversal_clifford(code).group_order
    else:
        assert starved.completeness is Completeness.UNKNOWN
        assert starved.group_order is None
        assert not starved.complete


def test_partition_structure_route_declines_rather_than_guesses() -> None:
    """``method='structure'`` must return UNKNOWN, never a partial count."""

    code = _stacked(CSSCode(*REGISTRY["steane"].build()))
    result = partition_clifford_group(
        code, [tuple(range(code.n))], method="structure"
    )
    assert result.completeness in (Completeness.COMPLETE, Completeness.UNKNOWN)
    if result.completeness is Completeness.UNKNOWN:
        assert result.group_order is None
