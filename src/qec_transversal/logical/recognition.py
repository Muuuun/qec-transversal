r"""Certified fullness for large ``k``: the McLaughlin transvection route.

Deciding ``G = Sp(2k, 2)`` by computing ``|G|`` becomes infeasible well before
``k = 20``, yet fullness is exactly the question a transversal-gate census
wants answered.  This module implements a *recognition* certificate instead of
an order computation, based on McLaughlin's classification of irreducible
groups generated by symplectic transvections: a transvection-generated group
acting irreducibly, with a transvection-direction orbit spanning the space and
no invariant quadratic form, is the full symplectic group unless it is one of
the excluded symmetric-group cases -- which are ruled out by an exact
element-order argument (:func:`..utils.permutations._symmetric_group_element_orders`).

Every sub-certificate is exact.  The verdict is ``"full"`` (certified),
``"not-full"`` (a *verified* invariant subspace or quadratic form excludes
fullness), or ``"inconclusive"`` -- never a guess.
"""

