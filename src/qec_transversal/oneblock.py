def symplectic_transvection(direction: np.ndarray) -> np.ndarray:
    """The symplectic transvection ``t_v : x -> x + <x, v> v`` (row action).

    With the repository's form ``[[0, I], [I, 0]]``, ``<x, v>`` is the dot
    product of ``x`` with the half-swapped ``v``, so the matrix is
    ``I + outer(J v, v)``.
    """

    v = np.asarray(direction, dtype=np.uint8) & 1
    two_k = v.shape[0]
    if two_k % 2 or not v.any():
        raise ValueError("direction must be a nonzero symplectic row vector")
    k = two_k // 2
    swapped = np.concatenate([v[k:], v[:k]])
    return (np.eye(two_k, dtype=np.uint8) ^ (swapped[:, None] & v[None, :])).astype(np.uint8)


def _transvection_direction(matrix: np.ndarray) -> np.ndarray | None:
    """The direction vector when ``matrix`` is a symplectic transvection.

    A symplectic matrix with ``rank(t - I) = 1`` is necessarily ``t_v`` with
    ``v`` spanning the row space of ``t - I`` (the rank-one block must be
    ``outer(J v, v)`` for the form to be preserved); the reconstruction is
    verified exactly before returning.
    """

    two_k = matrix.shape[0]
    difference = matrix ^ np.eye(two_k, dtype=np.uint8)
    if rank(difference) != 1:
        return None
    row_index = int(np.flatnonzero(difference.any(axis=1))[0])
    v = difference[row_index]
    try:
        candidate = symplectic_transvection(v)
    except ValueError:
        return None
    if np.array_equal(candidate, matrix):
        return v
    return None


# ---------------------------------------------------------------------------
# Element orders of symmetric groups (for the McLaughlin exclusion)
# ---------------------------------------------------------------------------

_SYMMETRIC_ORDER_CACHE: dict[int, frozenset[int]] = {}


def _symmetric_group_element_orders(m: int, *, cap: int = 4_000_000) -> frozenset[int]:
    """The exact set of element orders of ``S_m``.

    An element order is the lcm of a partition of ``m``; equivalently a
    product over distinct primes ``p`` of one power ``p^a``, with the sum of
    the chosen prime powers at most ``m``.  Dynamic programming over primes
    (order -> minimal spent budget) enumerates the set exactly.  This set is
    closed under divisors, which the recognition certificate relies on.
    """

    cached = _SYMMETRIC_ORDER_CACHE.get(m)
    if cached is not None:
        return cached
    best: dict[int, int] = {1: 0}
    for p in _primes_up_to(m):
        powers = []
        q = p
        while q <= m:
            powers.append(q)
            q *= p
        for order, spent in list(best.items()):
            for q in powers:
                cost = spent + q
                if cost <= m:
                    new_order = order * q
                    previous = best.get(new_order)
                    if previous is None or previous > cost:
                        best[new_order] = cost
            if len(best) > cap:
                raise RuntimeError("symmetric-order enumeration exceeded its cap")
    result = frozenset(best)
    _SYMMETRIC_ORDER_CACHE[m] = result
    return result


