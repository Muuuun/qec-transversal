"""One-block Clifford analysis over *varying* partitions and dualities.

Chakraborty-Gottesman (arXiv:2602.13395) prove that gadget sets built on one
FIXED partition or duality — sets closed under composition, hence constant
depth — can never realize the full logical Clifford group ``Sp(2k, 2)`` of a
single code block (strict transversality and code automorphisms for k >= 2,
bare permutations even for k = 1, fixed-duality fold gates for k >= 3).  The
same paper points out the loophole: depth-one fold-transversal layers over
*varying* partitions/dualities are not closed under composition, and their
compositions (non-constant-depth circuits of depth-one layers with error
correction in between) may generate everything.  arXiv:2602.09788 proves
exactly that for the middle Reed-Muller family ``RM(m/2-1, m)`` (the
registry's ``tesseract``, ``rm64``, ``rm256``): transversal plus varying-fold
gates generate the full addressable logical Clifford group on one block.

This module decides that question *per code*: it collects every certified
depth-one one-block layer the repository knows how to certify —

* strict transversal shears (:meth:`CSSCode.analyze_transversal`),
* diagonal fold layers ``S_M^Z`` / ``S_M^X`` and the fold-Hadamard for every
  certified involution (:mod:`.matching`), the involutions coming from the
  structural candidates of :mod:`.dualities`, the BLISS-discovered involutive
  duality, and involutions sampled from the Tanner automorphism group
  (:func:`.twofold.automorphism_involutions`),
* SWAP-class permutation gates from Tanner-graph automorphism generators
  (:mod:`.automorphisms`),

then certifies the group generated by their logical symplectic images
against ``|Sp(2k, 2)|``.  Certification tiers, chosen automatically:

``closure``
    Breadth-first element enumeration (:func:`.group.generated_group_order`)
    when it completes under a cap — exact at any ``k``.
``exact-order``
    Deterministic Schreier-Sims (:func:`.group.schreier_sims_order`) for
    moderate ``k``, compared with ``|Sp(2k, 2)|``.
``recognition``
    For large ``k``, a certified recognition route based on McLaughlin's
    classification of transvection groups (see
    :func:`recognize_full_symplectic`).  Every sub-certificate is exact; if
    any step fails the result downgrades instead of guessing.
``lower-bound``
    The honest fallback: the truncated closure count as a lower bound,
    ``is_full`` undecided.
``skipped``
    Nothing could be certified inside the time budget.

Every generator's logical action is taken only from certified analyses, so a
wrong exact answer is impossible; at worst the verdict is undecided.

Synthesis: :func:`factor_target` factors a target logical symplectic matrix
into an explicit word in the collected depth-one layers via a word-tracking
Schreier-Sims chain, with the chain's completeness cross-checked against the
independent order engine and every returned word verified by recomposition.

Known limits (deliberate, and load-bearing for how results may be quoted):

``is_full`` is one-sided.
    ``True`` is a certificate.  There is no ``False``: a code admits
    exponentially many involutions and this engine samples them, so a group
    short of the target means "the layers found do not suffice", never "the
    code cannot" — such rows report an exact order for the collected
    generating set with ``is_full`` undecided, i.e. a *lower bound* on the
    code's one-block group.
Orders are modulo Pauli.
    Generators are certified at the symplectic/GF(2) level: :mod:`.matching`
    checks that each stabilizer row's image lies in the stabilizer row space,
    not that it returns with sign ``+1``.  Sign defects form a character on
    the stabilizer group and are always killable by a Pauli, so the group
    orders are unaffected — but only the strict diagonal generators are
    actually run through the sign-exact Stim verifier (:mod:`.phase`); fold,
    permutation and partition layers are not.
Fold layers come from certified *matchings*, not only ZX dualities.
    :attr:`MatchingAnalysis.certified` does not require ``is_zx_duality``; a
    matching whose kernels certify contributes a legitimate depth-one layer
    either way.
The Levi (CNOT-network) units are NOT collected.
    Albert's fixed-matching group is ``N_M = <S_M^Z, S_M^X, L_M>``; this
    module takes only what :func:`.matching.analyze_matching` returns — the
    two diagonal families and the fold-Hadamard — so the Levi factor
    ``L_M`` (implemented in :mod:`.twofold`) is absent from every matching.
    Together with the permutation gates, which ``N_2fold`` does not contain,
    that makes this group and Albert's *incomparable*: neither contains the
    other, and an order above or below a published two-fold number is
    evidence about neither.
``factor_target`` is narrower than the order engine.
    Word-tracking chain construction currently fails past ``k >= 6`` and is
    refused outright for ``k > 8``, so the tesseract full-``Sp(12,2)`` result
    is certified but not yet convertible into an explicit circuit.  Generator
    provenance also records a label and involution index rather than the
    physical layer parameter, so a returned word is not yet directly
    executable on hardware.
"""

